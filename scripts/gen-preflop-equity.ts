// Generates src/lib/engine/preflopEquity.ts: heads-up equity of each of the 169 classes vs a random hand.
import { writeFileSync } from 'node:fs';
import { ALL_CLASSES, CLASS_COMBOS, COMBOS, rng } from '../src/lib/cards.ts';
import { evaluate7 } from '../src/lib/engine/evaluator.ts';

const rand = rng(12345);
const N = 60000;
const out: Record<string, number> = {};
for (const cls of ALL_CLASSES) {
  const [a, b] = COMBOS[CLASS_COMBOS[cls][0]];
  let win = 0;
  const dead = new Uint8Array(52);
  for (let it = 0; it < N; it++) {
    dead.fill(0);
    dead[a] = dead[b] = 1;
    const draw = () => {
      let c: number;
      do c = (rand() * 52) | 0;
      while (dead[c]);
      dead[c] = 1;
      return c;
    };
    const v1 = draw(), v2 = draw();
    const b1 = draw(), b2 = draw(), b3 = draw(), b4 = draw(), b5 = draw();
    const h = evaluate7(a, b, b1, b2, b3, b4, b5);
    const v = evaluate7(v1, v2, b1, b2, b3, b4, b5);
    win += h < v ? 1 : h === v ? 0.5 : 0;
  }
  out[cls] = Math.round((win / N) * 10000) / 10000;
}
const body = Object.entries(out).map(([k, v]) => `  "${k}": ${v},`).join('\n');
writeFileSync(new URL('../src/lib/engine/preflopEquity.ts', import.meta.url),
  `// Generated by scripts/gen-preflop-equity.ts — heads-up all-in equity vs a random hand (60k trials per class).\nexport const CLASS_EQUITY_VS_RANDOM: Record<string, number> = {\n${body}\n};\n`);
console.log('AA', out.AA, 'AKs', out.AKs, '72o', out['72o'], '32o', out['32o']);
